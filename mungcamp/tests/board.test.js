'use strict';
const { main } = require('./lib');
main(async ({ check, until, sleep, enter, person, presenceServer, shot, cleanup }) => {
  const server = await presenceServer(); cleanup(server.close);
  const a = await person({ nick: '보물멍' }), b = await person({ nick: '달림멍' });
  cleanup(a.close); cleanup(b.close);
  check(await enter(a.page, server.url, 'playground'), '놀이터 입장');
  await until(a.page, () => !!MC.app.state.sceneObj.game);
  await a.page.click('[data-pg="join"]');
  await until(a.page, () => !!MC.app.state.sceneObj.me);
  await a.page.click('[data-mode="board"]');
  check(await until(a.page, () => MC.app.state.sceneObj.game.mode === 'board'), '보물 레이스 선택');
  check(await a.page.locator('[data-pg="start"]').isEnabled(), '한 명도 시작 가능');
  await a.page.click('[data-pg="start"]');
  check(await until(a.page, () => MC.app.state.sceneObj.game.board?.order.includes('board-bot')), '혼자면 산책봇 참가');
  await a.page.click('.race-roll');
  check(await until(a.page, () => MC.app.state.sceneObj.game.board.seq === 1), '버튼으로 주사위와 말 이동');
  check(await until(a.page, () => MC.app.state.sceneObj.game.board.seq === 2), '산책봇이 자동으로 주사위 굴리기');
  await shot(a.page, 'board-solo');
  await a.page.click('[data-pg="leave"]');
  check(await until(a.page, () => !MC.app.state.sceneObj.game.board && document.querySelector('.race-game').hidden), '퇴장 시 판과 봇 정리');

  await enter(b.page, server.url, 'playground');
  await until(b.page, () => !!MC.app.state.sceneObj.game);
  await a.page.click('[data-pg="join"]'); await b.page.click('[data-pg="join"]');
  check(await until(a.page, () => MC.app.state.sceneObj.game.players.length === 2), '친구와 둘이 참가');
  await a.page.click('[data-pg="start"]');
  check(await until(b.page, () => MC.app.state.sceneObj.game.phase === 'playing' && MC.app.state.sceneObj.game.board.order.length === 2), '같은 보드판 공유');
  check(await b.page.locator('.race-roll').isDisabled(), '친구 차례에는 굴리기 비활성');
  await a.page.click('.race-roll');
  await until(b.page, () => MC.app.state.sceneObj.game.board.seq === 1);
  await until(a.page, () => MC.app.state.sceneObj.game.board.seq === 1);
  const stateA = await a.page.evaluate(() => JSON.stringify(MC.app.state.sceneObj.game.board));
  check(await until(b.page, s => JSON.stringify(MC.app.state.sceneObj.game.board) === s, stateA), '주사위·위치·차례 서버 동기화');
  const watcher = await person({ phone: true, nick: '구경멍' }); cleanup(watcher.close);
  await enter(watcher.page, server.url, 'playground');
  check(await until(watcher.page, () => MC.app.state.sceneObj.board.open), '늦게 온 친구도 실시간 관전');
  check(await watcher.page.locator('.race-roll').isDisabled(), '관전자는 굴리기 불가');
  await shot(watcher.page, 'board-mobile-spectator');
  const usable = () => {
    const game = document.querySelector('.race-game'), roll = document.querySelector('.race-roll'), r = roll.getBoundingClientRect();
    const cells = [...document.querySelectorAll('.race-cell')].every(c => {
      const box = c.getBoundingClientRect(), n = c.querySelector('b').getBoundingClientRect();
      return box.height >= 20 && n.top >= box.top && n.bottom <= box.bottom;
    });
    return !game.hidden && r.left >= 0 && r.right <= innerWidth && r.bottom < innerHeight && cells && document.documentElement.scrollWidth <= innerWidth && roll.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2));
  };
  check(await watcher.page.evaluate(usable), '휴대폰 세로 판과 주사위 화면 안 배치');
  await watcher.page.setViewportSize({ width: 844, height: 390 }); await sleep(250);
  check(await watcher.page.evaluate(usable), '휴대폰 가로 판과 주사위 화면 안 배치');
  await shot(watcher.page, 'board-mobile-landscape');
  await watcher.page.setViewportSize({ width: 320, height: 740 }); await sleep(250);
  check(await watcher.page.evaluate(usable), '작은 휴대폰 주사위 조작 공간');
  await shot(watcher.page, 'board-mobile-small');
  let turns = 0;
  while (turns++ < 80) {
    const g = await a.page.evaluate(() => MC.app.state.sceneObj.game);
    if (g.phase === 'ended') break;
    const p = g.board.order[g.board.turn] === await a.page.evaluate(() => MC.app.net.id) ? a.page : b.page;
    await until(p, () => !document.querySelector('.race-roll').disabled);
    await p.click('.race-roll');
    await until(a.page, seq => MC.app.state.sceneObj.game.board.seq > seq, g.board.seq);
  }
  check(await until(a.page, () => MC.app.state.sceneObj.game.phase === 'ended' && !!MC.app.state.sceneObj.game.board.winner), '실제 판을 끝까지 플레이해 승리');
  check(await until(b.page, () => MC.app.state.sceneObj.game.phase === 'ended'), '친구에게 승패 공유');
  await shot(a.page, 'board-winner');
  await a.page.click('[data-pg="start"]');
  check(await until(b.page, () => MC.app.state.sceneObj.game.phase === 'playing' && MC.app.state.sceneObj.game.board.seq === 0 && Object.values(MC.app.state.sceneObj.game.board.positions).every(n => n === 0)), '한 판 더로 출발점 초기화');
  await b.page.click('[data-pg="leave"]');
  check(await until(a.page, () => MC.app.state.sceneObj.game.phase === 'ended'), '친구 퇴장 처리');
  await a.page.click('.race-back');
  await until(watcher.page, () => MC.app.state.sceneObj.game.phase === 'ended');
  await watcher.page.click('.race-back'); await b.page.click('.race-back');
  await b.page.click('[data-pg="join"]'); await watcher.page.click('[data-pg="join"]');
  const fourth = await person({ nick: '네번째멍' }); cleanup(fourth.close);
  await enter(fourth.page, server.url, 'playground');
  await until(fourth.page, () => !!MC.app.state.sceneObj.game);
  await fourth.page.click('[data-pg="join"]');
  check(await until(a.page, () => MC.app.state.sceneObj.game.players.length === 4), '네 명이 함께 참가');
  await a.page.click('[data-pg="start"]');
  check(await until(watcher.page, () => MC.app.state.sceneObj.game.phase === 'playing' && MC.app.state.sceneObj.game.board.order.length === 4 && document.querySelectorAll('.race-roster li').length === 4), '네 말과 네 이름 표시');
  await watcher.page.setViewportSize({ width: 320, height: 568 }); await sleep(250);
  check(await watcher.page.evaluate(usable), '높이가 짧은 휴대폰에서도 네 명의 판 조작');
  await shot(watcher.page, 'board-four-mobile-short');
  await until(a.page, () => !document.querySelector('.race-roll').disabled); await a.page.click('.race-roll');
  await until(b.page, () => !document.querySelector('.race-roll').disabled); await b.page.click('.race-roll');
  await until(watcher.page, () => !document.querySelector('.race-roll').disabled);
  const tap = await watcher.page.locator('.race-roll').boundingBox();
  await watcher.page.touchscreen.tap(tap.x + tap.width / 2, tap.y + tap.height / 2);
  check(await until(a.page, () => MC.app.state.sceneObj.game.board.seq === 3), '휴대폰 터치로 자기 차례 주사위 굴리기');
  await b.page.click('[data-pg="leave"]'); await watcher.page.click('[data-pg="leave"]'); await fourth.page.click('[data-pg="leave"]');
  await until(a.page, () => MC.app.state.sceneObj.game.phase === 'ended');
  await a.page.click('.race-back');
  await a.page.click('[data-mode="volley"]');
  check(await until(a.page, () => MC.app.state.sceneObj.game.mode === 'volley' && !document.querySelector('#session').classList.contains('board-open')), '다른 놀이로 전환');
  await a.page.click('#exitBtn');
  check(await until(a.page, () => !document.querySelector('.race-game') && !document.querySelector('#session').classList.contains('is-board')), '놀이터를 나가면 보드 UI 제거');
  check(!a.errors.length && !b.errors.length && !watcher.errors.length && !fourth.errors.length, '브라우저 오류 없음', [...a.errors, ...b.errors, ...watcher.errors, ...fourth.errors]);
});
