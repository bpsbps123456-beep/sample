'use strict';
const assert = require('assert/strict');
const B = require('../js/board-rules');
const Playground = require('../server/playground');
let s = B.create(['a', 'b'], 1000);
assert.deepEqual(s.order, ['a', 'b']);
assert.equal(B.roll(s, 7, 1100), false);
assert.equal(s.seq, 0);
B.roll(s, 4, 1200);
assert.equal(s.positions.a, 10, '지름길은 착지한 칸에서 한 번 적용');
assert.deepEqual(s.last, { id: 'a', dice: 4, from: 0, landed: 4, to: 10, auto: false });
assert.equal(s.turn, 1);
s.positions.b = 8; B.roll(s, 1, 2000);
assert.equal(s.positions.b, 6, '미끄럼은 뒤로 이동');
s.positions.a = 29; B.roll(s, 6, 3000);
assert.equal(s.positions.a, 30, '정확한 수 없이도 도착');
assert.equal(s.winner, 'a');
assert.equal(B.roll(s, 2, 5000), false, '끝난 판 추가 이동 금지');
assert.deepEqual(B.create(['a']).order, ['a', B.bot], '혼자 시작하면 산책봇과 대결');

const now = Date.now;
let time = 100000;
Date.now = () => time;
try {
  const messages = [], room = { members: new Set(), changed: new Map() };
  const game = new Playground(room, (c, m) => messages.push({ id: c.id, ...m }));
  const client = id => { const c = { id, state: { n: id, p: 'playground', x: 700, y: 760 } }; room.members.add(c); return c; };
  const a = client('a'), b = client('b'), c = client('c'), d = client('d'), spectator = client('spectator');
  game.command(a, 'join'); game.command(spectator, 'mode', 'board');
  assert.equal(game.mode, 'tag', '관전자 모드 변경 금지');
  game.command(a, 'mode', 'board'); game.command(a, 'start');
  assert.equal(game.phase, 'playing'); assert.ok(game.board.order.includes(B.bot));
  const key = `${game.round}:0`;
  game.command(spectator, 'roll', key); assert.equal(game.board.seq, 0, '관전자 주사위 금지');
  game.command(a, 'roll', key); assert.equal(game.board.seq, 1);
  const position = game.board.positions.a;
  game.command(a, 'roll', key); assert.equal(game.board.positions.a, position, '중복 요청 무시');
  time = game.board.deadline; game.tick(time);
  assert.equal(game.board.seq, 2, '산책봇 자동 차례'); assert.equal(game.board.last.id, B.bot);
  const seq = game.board.seq;
  game.command(a, 'roll', `${game.round}:${seq}`); assert.equal(game.board.seq, seq, '말 이동 중 굴리기 금지');
  time += 2000;
  game.board.positions.a = 29;
  game.command(a, 'roll', `${game.round}:${seq}`);
  assert.equal(game.phase, 'ended'); assert.match(game.result, /a 승리/);
  game.command(a, 'start'); assert.equal(game.board.seq, 0, '새 판 초기화');
  game.command(a, 'roll', `${game.round - 1}:0`); assert.equal(game.board.seq, 0, '이전 판 요청 차단');
  game.leave(a); assert.equal(game.phase, 'lobby'); assert.equal(game.board, null, '혼자 나가면 봇도 정리');

  game.command(a, 'join'); game.command(b, 'join'); game.command(c, 'join'); game.command(d, 'join');
  game.command(spectator, 'join'); assert.equal(game.players.size, 4, '네 명 정원');
  game.command(b, 'start'); assert.equal(game.phase, 'lobby', '방장만 시작');
  game.command(a, 'start'); assert.equal(game.board.order.length, 4); assert.ok(!game.board.order.includes(B.bot));
  game.command(b, 'roll', `${game.round}:0`); assert.equal(game.board.seq, 0, '다른 사람 차례 조작 금지');
  const moved = game.move(a, { ...a.state, x: 710, w: 1 }, time + 100);
  assert.equal(moved.x, a.state.x); assert.equal(moved.w, 0, '판 위에서는 달리기 중지');
  game.leave(b); assert.equal(game.board.order[game.board.turn], 'a', '다른 멍이 퇴장 후 차례 보존');
  game.leave(a); assert.equal(game.board.order[game.board.turn], 'c', '현재 멍이 퇴장 후 다음 차례');
  assert.equal(game.snapshot().host, 'c', '방장 승계');
  time = game.board.deadline; game.tick(time);
  assert.equal(game.board.last.id, 'c'); assert.equal(game.board.last.auto, true, '시간 초과 자동 굴림');
  game.leave(c); assert.equal(game.phase, 'ended'); assert.equal(game.board.winner, 'd', '한 명만 남으면 승리');
  game.leave(d); assert.equal(game.phase, 'lobby'); assert.equal(game.board, null);
  game.command(a, 'join'); game.command(a, 'mode', 'tag');
  game.command(a, 'start'); assert.equal(game.phase, 'lobby', '기존 술래잡기는 두 명 이상');
  console.log('✓ 보물 레이스 이동·승리·봇·권한·중복·차례·퇴장·타임아웃·재시작 검증');
} finally { Date.now = now; }
