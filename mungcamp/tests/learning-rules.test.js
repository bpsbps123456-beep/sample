'use strict';
const assert = require('assert/strict'), Learning = require('../server/learning');
const clients = new Set();
const lesson = new Learning(() => {}, () => clients);
const client = id => { const c = { id, state: { n: id }, room: { place: 'learn' } }; clients.add(c); return c; };
const owner = client('owner'), a = client('a'), b = client('b');
lesson.command(owner, 'enter', '8624'); lesson.command(a, 'enter', '0000'); lesson.command(b, 'enter', '0000');
assert.equal(owner.learn.role, 'owner'); assert.equal(a.learn.role, 'member');
lesson.command(a, 'start', { text: '위조 질문', type: 'text' }); assert.equal(lesson.question, null);
lesson.command(owner, 'start', { text: '좋아하는 계절?', type: 'choice', options: ['봄', '여름'] });
lesson.command(a, 'answer', { id: 1, answer: 0 }); lesson.command(b, 'answer', { id: 1, answer: 1 });
assert.equal(lesson.snapshot(a).boards.a.text, '봄'); assert.equal(lesson.snapshot(b).boards.a.text, undefined);
assert.equal(lesson.snapshot(owner).boards.a.text, undefined); assert.equal(lesson.snapshot(owner).summary, null);
lesson.command(a, 'reveal'); assert.equal(lesson.phase, 'open');
lesson.command(owner, 'close'); lesson.command(a, 'answer', { id: 1, answer: 1 }); assert.equal(lesson.answers.get('a').value, 0);
lesson.command(owner, 'reveal'); assert.deepEqual(lesson.summary(), [{ text: '봄', count: 1 }, { text: '여름', count: 1 }]);
assert.equal(lesson.snapshot(b).boards.a.text, '봄');
assert.equal(lesson.snapshot(owner).boards.a.text, undefined);
assert.deepEqual(lesson.snapshot(owner).summary, [{ text: '봄', count: 1 }, { text: '여름', count: 1 }]);
lesson.command(owner, 'start', { text: '친구에게 한 마디', type: 'text' }); assert.equal(lesson.answers.size, 0);
lesson.command(a, 'answer', { id: 1, answer: '이전 질문 답' }); assert.equal(lesson.answers.size, 0);
lesson.command(a, 'answer', { id: 2, answer: '같이 놀기' }); lesson.command(b, 'answer', { id: 2, answer: '같이 놀기' });
lesson.command(owner, 'reveal'); assert.deepEqual(lesson.summary(), [{ text: '같이 놀기', count: 2 }]);
const stranger = client('stranger'); lesson.command(stranger, 'enter', 'bad'); assert.ok(!stranger.learn);
owner.learn.until = 0; lesson.command(owner, 'reset'); assert.equal(lesson.phase, 'revealed');
console.log('✓ 배움터 비밀번호·운영 권한·개인 답 비공개·마감·공개·익명 집계·이전 질문 차단·인증 만료');
