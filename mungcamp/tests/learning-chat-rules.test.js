'use strict';
const assert = require('assert/strict'), Learning = require('../server/learning');
const clients = new Set(), sent = [];
const lesson = new Learning((c, m) => sent.push({ to: c.id, ...structuredClone(m) }), () => clients);
const client = id => { const c = { id, state: { n: id }, room: { place: 'learn' } }; clients.add(c); return c; };
const owner = client('owner'), a = client('a'), b = client('b'), outsider = client('outsider');
for (const [c, pin] of [[owner, '8624'], [a, '0000'], [b, '0000']]) lesson.command(c, 'enter', pin);
sent.length = 0; lesson.command(outsider, 'chat', '무단 대화');
assert.equal(lesson.messages.length, 0); assert.ok(sent.every(m => m.to === 'outsider'));
lesson.command(a, 'chat', '  함께\n이야기해요 <b>멍!</b>  ');
assert.equal(lesson.messages[0].text, '함께 이야기해요 <b>멍!</b>');
assert.deepEqual(sent.filter(m => m.t === 'learn-chat').map(m => m.to).sort(), ['a', 'b', 'owner']);
lesson.command(a, 'chat', '너무 빠른 연속 전송'); assert.equal(lesson.messages.length, 1);
assert.equal(sent.at(-1).t, 'learn-chat-error');
lesson.command(owner, 'chat', '반가워요'); assert.equal(lesson.messages[1].role, 'owner');
lesson.chatHistory(b); assert.equal(sent.at(-1).history, true); assert.equal(sent.at(-1).messages.length, 2);
lesson.command(a, 'clear-chat'); assert.equal(lesson.messages.length, 2);
lesson.command(owner, 'start', { type: 'text', text: '비공개 질문' });
a.learn.chatAt = 0; lesson.command(a, 'answer', { id: 1, answer: '나만 아는 답' });
lesson.command(a, 'chat', '친구에게 인사');
assert.equal(lesson.snapshot(owner).boards.a.text, undefined);
assert.ok(!JSON.stringify(lesson.messages).includes('나만 아는 답'));
for (let i = 0; i < 60; i++) { a.learn.chatAt = 0; lesson.command(a, 'chat', '멍'.repeat(200) + i); }
assert.equal(lesson.messages.length, 50); assert.equal(Array.from(lesson.messages.at(-1).text).length, 180);
assert.ok(lesson.messages[0].id < lesson.messages.at(-1).id);
const count = lesson.messages.length; b.room = { place: 'map' }; lesson.command(b, 'chat', '마을에서 보낸 말');
assert.equal(lesson.messages.length, count);
lesson.command(owner, 'clear-chat'); assert.equal(lesson.messages.length, 0);
assert.equal(sent.at(-1).t, 'learn-chat-clear');
console.log('✓ 대화 입장 권한·교실 한정 전송·운영자 대화·도배 제한·길이 제한·최근 기록·운영자 기록 지우기·답안 비공개 유지');
