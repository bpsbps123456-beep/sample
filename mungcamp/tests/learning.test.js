'use strict';
const { main } = require('./lib');
main(async ({ check, until, person, presenceServer, staticServer, cleanup, shot, sleep }) => {
  const server = await presenceServer(); cleanup(server.close);
  const owner = await person({ nick: '선생멍' }), a = await person({ nick: '생각멍' }), b = await person({ nick: '새싹멍', phone: true });
  for (const p of [owner, a, b]) cleanup(p.close);
  const enter = async (p, pin) => {
    await p.goto(server.url); await until(p, () => MC.app.net.id && MC.app.net.online);
    await p.click('#learnBtn'); await p.fill('#learnPin', pin); await p.press('#learnPin', 'Enter');
    return until(p, () => MC.app.state.scene === 'learn' && !!MC.app.state.sceneObj.lesson?.roster.length);
  };
  await owner.page.goto(server.url); await until(owner.page, () => MC.app.net.id);
  const denied = await owner.page.evaluate(() => new Promise(resolve => {
    const ws = new WebSocket(location.origin.replace(/^http/, 'ws'));
    const timer = setTimeout(() => { ws.close(); resolve(false); }, 4000);
    ws.onopen = () => ws.send(JSON.stringify({ t: 's', s: { p: 'learn', x: 500, y: 500 } }));
    ws.onmessage = e => { if (JSON.parse(e.data).t === 'learn-denied') { clearTimeout(timer); ws.close(); resolve(true); } };
  }));
  check(denied, '비밀번호 없이 웹소켓으로 교실에 직접 들어가는 요청 차단');
  check(await owner.page.evaluate(() => document.querySelector('#learnBtn').getBoundingClientRect().right <= document.querySelector('#dressBtn').getBoundingClientRect().left), '꾸미기 왼쪽에 배움터 버튼');
  await owner.page.click('#learnBtn'); await owner.page.fill('#learnPin', '1234'); await owner.page.click('.learn-gate [type="submit"]');
  check(await until(owner.page, () => document.querySelector('.learn-gate .learn-error').textContent.includes('맞지')), '잘못된 비밀번호 차단');
  await owner.page.fill('#learnPin', '8624'); await owner.page.click('.learn-gate [type="submit"]');
  check(await until(owner.page, () => MC.app.state.sceneObj?.lesson?.role === 'owner'), '운영자 권한 부여');
  check(await enter(a.page, '0000') && await enter(b.page, '0000'), 'PC·휴대폰 참여자 입장');
  check(await until(owner.page, () => MC.app.state.sceneObj.lesson.online === 2), '실시간 참여 인원');
  await a.page.evaluate(() => MC.app.net.link.learn('start', { type: 'text', text: '권한 위조' })); await sleep(250);
  check(await owner.page.evaluate(() => !MC.app.state.sceneObj.lesson.question), '참여자의 운영 명령 차단');
  await owner.page.click('.learn-open-owner');
  await owner.page.fill('[name="question"]', '오늘 어떤 활동을 하고 싶나요?'); await owner.page.fill('[name="options"]', '숲 산책\n멍이 배구\n책 읽기');
  await owner.page.click('.learn-question-form [type="submit"]');
  check(await until(b.page, () => MC.app.state.sceneObj.lesson.question?.type === 'choice'), '객관식 질문 공유');
  await a.page.check('.learn-answer-form input[value="1"]'); await a.page.click('.learn-answer-form [type="submit"]');
  await b.page.check('.learn-answer-form input[value="0"]'); await b.page.click('.learn-answer-form [type="submit"]');
  check(await until(owner.page, () => MC.app.state.sceneObj.lesson.answered === 2), '제출 인원 집계');
  const aid = await a.page.evaluate(() => MC.app.net.id);
  check(await a.page.evaluate(id => MC.app.state.sceneObj.lesson.boards[id].text === '멍이 배구', aid), '본인 팻말은 즉시 표시');
  check(await b.page.evaluate(id => !MC.app.state.sceneObj.lesson.boards[id].text, aid), '공개 전 친구 답 전송 안 함');
  check(await owner.page.evaluate(id => !MC.app.state.sceneObj.lesson.boards[id].text && MC.app.state.sceneObj.lesson.summary === null, aid), '공개 전 운영자에게도 개별 답 비공개');
  await sleep(2500); await shot(b.page, 'learning-phone-private');
  await owner.page.click('.learn-open-owner'); await owner.page.click('[data-command="close"]');
  check(await until(a.page, () => document.querySelector('.learn-answer-form [type="submit"]').disabled), '응답 마감 후 수정 차단');
  await owner.page.click('[data-command="reveal"]');
  check(await until(b.page, id => MC.app.state.sceneObj.lesson.boards[id]?.text === '멍이 배구', aid), '답 공개 시 팻말 표시');
  check(await until(owner.page, () => { const s = MC.app.state.sceneObj.lesson.summary; return s?.length === 3 && s[0].count === 1 && s[1].count === 1 && s[2].count === 0 && s.every(r => Object.keys(r).length === 2); }), '익명 선택지별 인원 취합');
  check(await owner.page.evaluate(id => !MC.app.state.sceneObj.lesson.boards[id].text, aid), '공개 후에도 운영자는 이름별 답 없이 취합 결과만');
  await shot(owner.page, 'learning-owner-results');
  await owner.page.selectOption('.learn-question-form [name="type"]', 'text');
  await owner.page.fill('[name="question"]', '친구에게 전하고 싶은 말은?'); await owner.page.click('.learn-question-form [type="submit"]');
  check(await until(a.page, () => MC.app.state.sceneObj.lesson.question?.id === 2 && !MC.app.state.sceneObj.lesson.own), '새 질문에서 이전 답 초기화');
  for (const p of [a.page, b.page]) { await p.fill('.learn-answer-form textarea', '함께해서 즐거워요 <b>멍!</b>'); await p.click('.learn-answer-form [type="submit"]'); }
  await until(owner.page, () => MC.app.state.sceneObj.lesson.answered === 2);
  await owner.page.click('.learn-open-owner'); await owner.page.click('[data-command="reveal"]');
  check(await until(owner.page, () => MC.app.state.sceneObj.lesson.summary?.[0]?.count === 2), '같은 주관식 답을 익명 취합');
  check(await b.page.evaluate(() => !document.querySelector('.learn-sign b')), 'HTML 답안을 글자로 표시');
  await owner.page.click('[data-dismiss]');
  await shot(owner.page, 'learning-desktop-revealed'); await shot(b.page, 'learning-phone-revealed');
  check(await b.page.evaluate(() => { const f = document.querySelector('.learn-floor').getBoundingClientRect(), response = document.querySelector('.learn-response'), r = response.getBoundingClientRect(), h = document.querySelector('.learn-board').getBoundingClientRect(); return f.top >= h.bottom && (response.hidden ? f.bottom <= innerHeight : f.bottom <= r.top && r.bottom <= innerHeight) && document.documentElement.scrollWidth === innerWidth; }), '휴대폰 칠판·멍이·조작부 겹침 방지');
  await b.page.setViewportSize({ width: 844, height: 390 }); await sleep(200); await shot(b.page, 'learning-phone-landscape');
  await owner.page.click('.learn-open-owner');
  await owner.page.selectOption('.learn-question-form [name="type"]', 'choice');
  await owner.page.fill('[name="question"]', '생각'.repeat(120));
  await owner.page.fill('[name="options"]', Array.from({ length: 6 }, (_, i) => '가'.repeat(79) + i).join('\n'));
  await owner.page.click('.learn-question-form [type="submit"]');
  check(await until(b.page, () => MC.app.state.sceneObj.lesson.question?.text.length === 240 && MC.app.state.sceneObj.lesson.question.options.length === 6 && MC.app.net.online), '최대 길이 한글 질문과 여섯 보기를 연결 끊김 없이 공유');
  await owner.page.click('.learn-open-owner'); await owner.page.click('[data-command="reset"]');
  check(await until(b.page, () => !MC.app.state.sceneObj.lesson.question && !MC.app.state.sceneObj.lesson.own && MC.app.state.sceneObj.lesson.phase === 'waiting'), '칠판 비우기로 질문·답·취합 결과 정리');
  await owner.page.click('[data-dismiss]');
  await a.page.click('#exitBtn');
  check(await until(a.page, () => MC.app.state.view === 'home' && !document.querySelector('.learning-room') && !document.querySelector('.learn-owner')), '퇴장 시 배움터 UI 제거');
  check(await until(owner.page, () => MC.app.state.sceneObj.lesson.online === 1), '퇴장 인원 반영');
  check((await fetch(server.url + 'server/learning.js')).status === 404, '서버 비밀번호 소스 접근 차단');
  const staticSite = await staticServer(); cleanup(staticSite.close);
  await a.page.goto(staticSite.url); await until(a.page, () => MC.app.net.kind === 'channel');
  await a.page.click('#learnBtn'); await a.page.fill('#learnPin', '0000'); await a.page.click('.learn-gate [type="submit"]');
  check(await until(a.page, () => document.querySelector('.learn-gate .learn-error').textContent.includes('서버')), '서버 없는 환경 안내');
  check(!owner.errors.length && !a.errors.length && !b.errors.length, '배움터 브라우저 오류 없음', owner.errors.concat(a.errors, b.errors));
});
