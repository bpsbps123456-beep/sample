'use strict';
const { main } = require('./lib');
main(async ({ check, until, sleep, enter, person, presenceServer, staticServer, shot, cleanup }) => {
  const server = await presenceServer(); cleanup(server.close);
  const a = await person({ nick: '산책멍' }), b = await person({ nick: '숨는멍' });
  cleanup(a.close); cleanup(b.close);
  check(await enter(a.page, server.url, 'playground'), '글램핑 옆 놀이터 입장');
  check(await a.page.evaluate(async () => {
    await MC.PlaygroundArt.ready;
    return MC.PlaygroundArt.loaded === 5 && !MC.PlaygroundArt.failed.length;
  }), '놀이터 SVG 다섯 종류 실제 디코딩');
  // 운영 사이트는 HTTPS에서 자동 등록한다. 로컬 시험 서버는 직접 등록한다.
  await a.page.evaluate(() => navigator.serviceWorker.register('sw.js'));
  check(await until(a.page, async () => {
    if (!navigator.serviceWorker.controller) return false;
    const cache = await caches.open('mungcamp-v64');
    return !!(await cache.match('assets/playground/gate.svg')) && !!(await cache.match('assets/playground/tree.svg'));
  }), '새 오프라인 캐시에 SVG 저장');
  check(await enter(b.page, server.url, 'playground'), '두 번째 친구 놀이터 입장');
  check(await until(a.page, () => MC.app.state.sceneObj.game && MC.app.net.list('playground').length === 1), '서버로 친구 연결');
  await a.page.click('[data-pg="join"]');
  await until(a.page, () => MC.app.state.sceneObj.game.players.length === 1);
  check(await a.page.locator('[data-pg="start"]').isDisabled(), '한 명일 때 시작 비활성');
  await b.page.click('[data-pg="join"]');
  check(await until(a.page, () => MC.app.state.sceneObj.game.players.length === 2), '참가자 목록 공유');
  await a.page.click('[data-mode="hide"]');
  check(await until(b.page, () => MC.app.state.sceneObj.game.mode === 'hide'), '놀이 선택 공유');
  await shot(a.page, 'playground-lobby');
  await a.page.click('[data-pg="start"]');
  check(await until(b.page, () => MC.app.state.sceneObj.game.phase === 'ready'), '준비 시간 시작');
  await until(a.page, () => MC.app.state.sceneObj.game.phase === 'ready');
  const aSeeker = await a.page.evaluate(() => MC.app.state.sceneObj.game.seeker === MC.app.net.id);
  const seeker = aSeeker ? a.page : b.page, runner = aSeeker ? b.page : a.page;
  check(await seeker.evaluate(() => MC.app.state.sceneObj.frozen), '준비 중 술래 이동 차단');
  const before = await runner.evaluate(() => MC.app.state.sceneObj.player.x);
  await runner.keyboard.down('ArrowLeft'); await sleep(300); await runner.keyboard.up('ArrowLeft');
  check(await runner.evaluate(x => MC.app.state.sceneObj.player.x < x - 15, before), '방향키로 달리기');
  await runner.evaluate(() => { MC.app.state.sceneObj.target = { x: 480, y: 610 }; });
  check(await until(runner, () => Math.hypot(MC.app.state.sceneObj.player.x - 480, MC.app.state.sceneObj.player.y - 610) < 6), '덤불까지 이동');
  await runner.click('[data-act="play"]');
  check(await until(runner, () => MC.app.state.sceneObj.hidden), '숨기 버튼');
  check(await until(seeker, () => [...MC.app.state.sceneObj.visitors.values()].some(v => v.st.hd)), '숨은 상태 서버 공유');
  check(await until(seeker, () => MC.app.state.sceneObj.game.phase === 'playing', null, 18000), '준비 후 같은 라운드 시작');
  check(await seeker.evaluate(() => { const sc = MC.app.state.sceneObj; return [...sc.visitors].every(([id, v]) => !v.st.hd || !sc.visible(id, v)); }), '숨어 있는 멍이를 술래 화면에서 감춤');
  await shot(runner, 'playground-hiding');
  await runner.keyboard.down('ArrowDown'); await sleep(180); await runner.keyboard.up('ArrowDown');
  check(await until(runner, () => !MC.app.state.sceneObj.hidden), '움직이면 숨기 해제');
  await seeker.keyboard.press('KeyC');
  await seeker.click('[data-pg="leave"]');
  check(await until(runner, () => MC.app.state.sceneObj.game.phase === 'ended'), '술래 참가 취소 시 종료');
  await a.page.click('#exitBtn');
  check(await until(a.page, () => MC.app.state.view === 'home'), '나가기 후 글램핑 옆으로 복귀');
  check(await until(a.page, () => !document.querySelector('.playground-panel') && MC.app.camp.near?.id === 'playground'), '놀이터 UI 제거 및 입구 복귀');
  check(await a.page.evaluate(() => { const c = MC.app.camp, p = c.spots.find(s => s.id === 'playground'), t = c.spots.find(s => s.id === 'tent'); return p.x > t.x && Math.abs(p.y - t.y) < 250; }), '6시 글램핑 오른쪽에 통합 배치');
  await shot(a.page, 'playground-map');
  const phone = await person({ phone: true, nick: '작은멍' }); cleanup(phone.close);
  check(await enter(phone.page, server.url, 'playground'), '휴대폰 놀이터 입장');
  check(await until(phone.page, () => !!MC.app.state.sceneObj.game), '휴대폰 연결');
  await phone.page.click('[data-pg="join"]');
  check(await until(phone.page, () => !!MC.app.state.sceneObj.me), '휴대폰 참가');
  await sleep(2600);
  const tap = await phone.page.evaluate(() => { const sc = MC.app.state.sceneObj; return { ...sc.toScreen(sc.player.x + 80, sc.player.y), before: sc.player.x }; });
  await phone.page.touchscreen.tap(tap.x, tap.y);
  check(await until(phone.page, x => MC.app.state.sceneObj.player.x > x + 50, tap.before), '휴대폰에서 땅을 톡 눌러 이동');
  await phone.page.click('[data-panel="sound"]');
  check(await phone.page.evaluate(() => {
    const button = document.querySelector('#panel-sound [data-close]'), r = button.getBoundingClientRect();
    return !document.querySelector('#panel-sound').hidden && button.contains(document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2));
  }), '놀이터 패널 위에서도 소리 설정 조작');
  await phone.page.click('#panel-sound [data-close]');
  check(await phone.page.evaluate(() => { const r = document.querySelector('.playground-panel').getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth && document.documentElement.scrollWidth <= innerWidth; }), '휴대폰 패널 화면 안 배치');
  await shot(phone.page, 'playground-mobile');
  await phone.page.setViewportSize({ width: 844, height: 390 });
  await sleep(200); await shot(phone.page, 'playground-mobile-landscape');
  check(await phone.page.evaluate(() => { const p = document.querySelector('.playground-panel'), r = p.getBoundingClientRect(), b = p.querySelector('[data-pg="leave"]').getBoundingClientRect(); return r.right < innerWidth / 2 && b.bottom <= r.bottom && r.bottom < innerHeight; }), '휴대폰 가로 화면 참가 버튼과 놀이 공간 확보');
  const offline = await staticServer(); cleanup(offline.close);
  await enter(phone.page, offline.url, 'playground');
  check(await phone.page.locator('[data-pg="join"]').isDisabled(), '서버 없는 정적 사이트에서는 연결 안내');
  check(!a.errors.length && !b.errors.length && !phone.errors.length, '브라우저 오류 없음', [...a.errors, ...b.errors, ...phone.errors]);
});
