'use strict';
const assert = require('assert/strict');
const Playground = require('../server/playground');
const R = require('../js/playground-rules');
const messages = [];
const room = { members: new Set(), changed: new Map() };
const game = new Playground(room, (c, m) => messages.push({ id: c.id, ...m }));
const client = id => { const c = { id, state: { p: 'playground', n: id, ...R.spawn(0) } }; room.members.add(c); return c; };
const a = client('a'), b = client('b'), spectator = client('spectator');
game.command(a, 'join'); game.command(a, 'start');
assert.equal(game.phase, 'lobby', '한 명은 시작할 수 없다');
game.command(b, 'join'); game.command(spectator, 'mode', 'hide');
assert.equal(game.mode, 'tag', '비참가자는 모드를 바꿀 수 없다');
game.command(b, 'start'); assert.equal(game.phase, 'lobby', '방장만 시작한다');
game.command(a, 'mode', 'hide'); game.command(a, 'start');
assert.equal(game.phase, 'ready');
assert.equal(game.players.size, 2);
assert.ok(game.until > Date.now() + 14000, '숨을 준비 시간 15초');
const seeker = game.seeker === a.id ? a : b, runner = seeker === a ? b : a;
game.command(spectator, 'join'); assert.equal(game.players.size, 2, '진행 중에는 관전');
const at = Date.now();
const frozen = game.move(seeker, { ...seeker.state, x: seeker.state.x + 10 }, at + 120);
assert.equal(frozen.x, seeker.state.x, '준비 시간 술래 이동 금지');
runner.pgMoveAt = at;
const teleport = game.move(runner, { ...runner.state, x: 1200 }, at + 125);
assert.equal(teleport.x, runner.state.x, '순간 이동 거부');
Object.assign(runner.state, { x: 285, y: 235, w: 0 });
runner.pgMoveAt = at;
assert.equal(game.move(runner, { ...runner.state, hd: 1 }, at + 125).hd, 1, '덤불에서만 숨기');
assert.equal(game.move(runner, { ...runner.state, hd: 1, w: 1 }, at + 250).hd, 0, '움직이면 숨기 해제');
game.tick(game.until);
assert.equal(game.phase, 'playing');
Object.assign(seeker.state, { x: 100, y: 200 });
game.command(seeker, 'catch'); assert.equal(game.players.get(runner.id).caught, false, '먼 거리 잡기 거부');
Object.assign(seeker.state, { x: 963, y: 205 }); Object.assign(runner.state, { x: 1041, y: 205 });
assert.ok(R.valid(seeker.state.x, seeker.state.y) && R.valid(runner.state.x, runner.state.y));
game.lastCatch = 0; game.command(seeker, 'catch');
assert.equal(game.players.get(runner.id).caught, false, '나무를 사이에 둔 잡기 거부');
Object.assign(seeker.state, { x: 250, y: 235 }); Object.assign(runner.state, { x: 285, y: 235 });
game.lastCatch = 0; game.command(spectator, 'catch'); assert.equal(game.phase, 'playing', '관전자는 잡을 수 없다');
game.command(seeker, 'catch');
assert.equal(game.phase, 'ended'); assert.match(game.result, /술래의 승리/);
const previous = game.seeker;
game.command(a, 'mode', 'tag'); game.command(a, 'start');
assert.notEqual(game.seeker, previous, '다음 판은 다른 술래');
game.tick(game.until); game.tick(game.until);
assert.match(game.result, /친구들의 승리/, '시간이 끝나면 도망간 친구들 승리');
game.command(a, 'start');
game.leave(game.seeker === a.id ? a : b);
assert.equal(game.phase, 'ended', '술래 퇴장 시 라운드 종료');
const remaining = [...game.players.values()][0].client;
assert.equal(game.snapshot().host, remaining.id, '방장 퇴장 시 승계');
game.leave(remaining); assert.equal(game.phase, 'lobby');
assert.equal(game.players.size, 0);
for (let i = 0; i < 13; i++) game.command(client('friend' + i), 'join');
assert.equal(game.players.size, 12, '한 판은 열두 멍이까지');
for (const o of R.obstacles) assert.equal(R.valid(o.x + o.w / 2, o.y + o.h / 2), false);
for (let i = 0; i < 12; i++) assert.ok(R.valid(R.spawn(i).x, R.spawn(i).y));
console.log('✓ 놀이터: 참가·권한·준비·이동·숨기·거리·장애물·승패·재시작·퇴장 판정 통과');
