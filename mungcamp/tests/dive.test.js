'use strict';
const { main } = require('./lib');

main(async ({ check, presenceServer, person, until, sleep, shot, cleanup, enter }) => {
  const site = await presenceServer(); cleanup(() => site.close());
  const a = await person({ nick: '잠수멍' }), b = await person({ nick: '바다멍' });
  cleanup(() => a.close()); cleanup(() => b.close());
  const A = a.page, B = b.page;
  await enter(A, site.url, 'water'); await enter(B, site.url, 'water');
  await until(A, () => MC.app.state.started && MC.app.net.online);
  await sleep(2600);
  check(await A.evaluate(() => { const s = MC.app.state.sceneObj; return s.rippleAt() && !s.rippleAt(); }), '물수제비는 한 번씩 던진다');
  check(await until(A, () => { const s = MC.app.state.sceneObj; return !s.stone && s.ripples.length >= 3; }), '돌이 세 번 이상 튀고 물결을 남긴다');
  const origin = await A.evaluate(() => { const c = MC.app.state.sceneObj.crowd; return [c.me.X, c.me.Z]; });
  await A.keyboard.press('Shift'); // 기다리는 동안 자동으로 숨은 조작부를 깨운다.
  await A.click('[data-act=dive]');
  check(await until(A, () => { const s = MC.app.state.sceneObj; return s.underwater && s.pup.rest === 'dive' && s.pup.lie === 0 && s.crowd.state().dv === 1; }), '잠수 버튼으로 유리 헬멧과 공기통을 착용한다');
  check(await A.evaluate(() => document.querySelector('[data-act=dive]').textContent.includes('물 위로') && document.querySelector('[data-act=bottle]').hidden && document.querySelector('[data-act=chair]').hidden), '물속에서는 물 위로·공기 방울 버튼을 보여 준다');
  check(await until(B, () => { const c = MC.app.state.sceneObj.crowd; return [...c.visitors.values()].some(v => v.st.dv && !c.sees(v)); }), '물 위에서는 잠수한 친구가 따로 표시되지 않는다');
  await B.keyboard.press('Shift');
  await B.click('[data-act=dive]');
  check(await until(B, () => { const c = MC.app.state.sceneObj.crowd; return [...c.visitors.values()].some(v => v.st.dv && c.sees(v) && v.pup.rest === 'dive'); }), '서버를 통해 다른 잠수 친구의 장비와 상태를 공유한다');
  const before = await A.evaluate(() => MC.app.state.sceneObj.crowd.me.X);
  await A.keyboard.down('ArrowRight'); await sleep(650); await A.keyboard.up('ArrowRight');
  check(await A.evaluate(x => MC.app.state.sceneObj.crowd.me.X > x + 20, before), '방향키로 물속을 헤엄친다');
  const clam = await A.evaluate(() => {
    const s = MC.app.state.sceneObj; s.crowd.me.X = 720; s.dive.follow(720); s.crowd.layout();
    const q = s.dive.clam; return [q.x, q.y - 8];
  });
  await A.mouse.click(...clam);
  check(await A.evaluate(() => MC.app.state.sceneObj.dive.open > 0), '조개를 누르면 진주와 공기 방울을 보여 준다');
  await A.click('[data-act=ripple]');
  check(await A.evaluate(() => { const d = MC.app.state.sceneObj.dive; for (let i = 0; i < 100; i++) d.burst(100, 100, 8); return d.bubbles.length <= 70; }), '공기 방울을 반복해서 만들어도 입자 수가 제한된다');
  await shot(A, 'dive-desktop');
  await A.click('[data-act=dive]');
  check(await A.evaluate(o => { const s = MC.app.state.sceneObj; return !s.underwater && !s.crowd.state().dv && Math.hypot(s.crowd.me.X - o[0], s.crowd.me.Z - o[1]) < 3 && !s.floating; }, origin), '물 위로 돌아오면 잠수 전 자리로 복귀한다');
  check(await until(B, () => { const c = MC.app.state.sceneObj.crowd; return [...c.visitors.values()].some(v => !v.st.dv && !c.sees(v)); }), '잠수 중에는 물 위로 돌아간 친구를 숨긴다');
  await A.evaluate(() => { const s = MC.app.state.sceneObj; s.crowd.me.Z = -350; s.crowd.layout(); s.toggleDive(); s.toggleDive(); });
  check(await until(A, () => { const s = MC.app.state.sceneObj; return s.floating && s.pup.rest === 'tube' && s.pup.lie === 1; }), '튜브에서 잠수했다 돌아오면 다시 튜브에 뜬다');
  check(await A.evaluate(() => !MC.netClean({ p: 'map', x: 1, y: 2, dv: 1 }).dv), '잠수 상태는 바다에서만 허용한다');
  const phone = await person({ phone: true }); cleanup(() => phone.close());
  const P = phone.page; await enter(P, site.url, 'water'); await sleep(2600);
  check(await P.evaluate(() => { const b = document.querySelector('[data-act=dive]').getBoundingClientRect(); return b.left >= 0 && b.right <= innerWidth; }), '휴대폰에서 잠수 버튼이 잘리지 않는다');
  await P.click('[data-act=dive]');
  await P.mouse.click(275, 350);
  check(await until(P, () => MC.app.state.sceneObj.crowd.me.X > 175, null, 5000), '휴대폰에서 누른 곳으로 헤엄친다');
  await shot(P, 'dive-mobile');
  await P.setViewportSize({ width: 844, height: 390 });
  check(await until(P, () => { const s = MC.app.state.sceneObj; return s.w === 844 && s.underwater && s.pup.x >= 0 && s.pup.x <= s.w && s.dive.clam.y < s.h; }), '잠수 중 화면을 돌려도 수영 위치와 바다의 높이가 맞는다');
  await shot(P, 'dive-landscape');
  await A.evaluate(() => { const d = MC.app.state.sceneObj; d.ripples = []; for (let i = 0; i < 400; i++) d.update(1/60); });
  check(a.errors.length === 0 && b.errors.length === 0 && phone.errors.length === 0, '그리기·이동·복귀 중 오류 없음', [...a.errors, ...b.errors, ...phone.errors]);
});
