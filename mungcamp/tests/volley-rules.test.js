'use strict';
const assert = require('assert/strict');
const V = require('../js/volley-rules');
const Playground = require('../server/playground');
const s = V.create();
s.dogs[0].axis = 1; s.dogs[0].jump = true;
V.step(s, 1 / 120);
assert.ok(s.dogs[0].x > 205 && s.dogs[0].y < V.ground, '좌우 이동과 점프');
const vy = s.dogs[0].vy; s.dogs[0].jump = true; V.step(s, 1 / 120);
assert.ok(s.dogs[0].vy > vy, '공중에서 다시 점프하지 않는다');
for (let i = 0; i < 300; i++) V.step(s, 1 / 120);
assert.ok(s.dogs[0].x <= 433, '상대 코트로 넘어가지 못한다');
const net = V.create(); net.ball = { x: 450, y: 330, vx: 500, vy: 0 };
for (let i = 0; i < 5; i++) V.step(net, 1 / 120);
assert.ok(net.ball.x < V.net && net.ball.vx < 0, '네트 옆면 충돌');
const top = V.create(); top.ball = { x: 480, y: 264, vx: 0, vy: 100 };
for (let i = 0; i < 5; i++) V.step(top, 1 / 120);
assert.ok(top.ball.vy < 0 && top.ball.y < V.netTop, '네트 윗면 충돌');
const hit = V.create(); hit.ball = { x: 205, y: 310, vx: 0, vy: 200 };
V.step(hit, .02); assert.ok(hit.ball.vy < 0 && hit.ball.vx > 0, '멍이의 머리에 닿으면 공을 받아 넘긴다');
const floor = V.create(); floor.ball = { x: 600, y: 410, vx: 0, vy: 200 }; V.step(floor, .02);
assert.deepEqual(floor.score, [1, 0]); const score = floor.score.slice();
V.step(floor, .5); assert.deepEqual(floor.score, score, '서브 대기 중 중복 득점 없음');
floor.pause = 0; floor.score = [4, 0]; floor.ball = { x: 600, y: 411, vx: 0, vy: 200 }; V.step(floor, .02);
assert.equal(floor.winner, 0, '5점 선취 승리');
const room = { members: new Set(), changed: new Map() }, messages = [];
const game = new Playground(room, (c, m) => messages.push({ c, m }));
const make = id => { const c = { id, state: { p: 'playground', n: id, x: 600, y: 780 } }; room.members.add(c); return c; };
const a = make('왼멍'), b = make('오른멍'), viewer = make('관전멍');
game.command(a, 'join'); game.command(a, 'mode', 'volley'); game.command(b, 'join'); game.command(viewer, 'join');
assert.equal(game.players.size, 2, '배구 정원 두 명');
game.command(b, 'start'); assert.equal(game.phase, 'lobby', '방장만 시작');
game.command(a, 'start'); assert.equal(game.phase, 'ready');
game.tick(game.until); assert.equal(game.phase, 'playing');
game.command(viewer, 'input', 1); assert.equal(game.volley.dogs[0].axis, 0);
game.command(a, 'input', 999); assert.equal(game.volley.dogs[0].axis, 1, '입력 범위 정리');
game.command(a, 'jump'); const at = game.volley.lastAt; game.tick(at + 20);
assert.ok(game.volley.dogs[0].y < V.ground);
game.tick(at + 1000); assert.equal(game.volley.dogs[0].axis, 0, '끊긴 이동 입력 해제');
game.volley.score = [4, 0]; game.volley.pause = 0; game.volley.ball = { x: 600, y: 411, vx: 0, vy: 200 };
game.tick(game.volley.lastAt + 20); assert.equal(game.phase, 'ended'); assert.match(game.result, /왼멍 승리/);
game.command(a, 'start'); assert.deepEqual(game.volley.score, [0, 0], '새 판 점수 초기화');
game.leave(b); assert.equal(game.phase, 'ended'); assert.match(game.result, /친구가 나가서/);
game.command(a, 'mode', 'tag'); game.command(viewer, 'join'); game.command(make('세번째'), 'join');
game.command(a, 'mode', 'volley'); assert.equal(game.mode, 'tag', '세 명의 참가자를 배구 선택으로 내보내지 않는다');
console.log('✓ 배구 물리·머리로 받기·네트·점수·승패·권한·이동 입력·퇴장·재시작');
